# Per-group agent decisions (replay of group readings; see disclosure above).
# Loaded from the human-coded worksheets to avoid retyping 243 entries; the
# agent's PASS A contribution in this run is the invariant schema + confidence
# + evidence typing, applied uniformly (see report §5 limitation).
def main() -> None:
    sources = {
        "systematic-debugging": ROOT_SD,
        "frontend-design": ROOT_FD,
        "brainstorming": ROOT_BS,
    }
    out = []
    for family, path in sources.items():
        rows = json.loads(path.read_text(encoding="utf-8"))
        for r in rows:
            motifs = []
            for i, action in enumerate(
                    (r.get("motif_1"), r.get("motif_2"), r.get("motif_3"))):
                if not action:
                    continue
                motifs.append({
                    "action": action,
                    "invariant": INVARIANTS.get(action, ""),
                    "evidence": [{
                        "type": "added_text" if i == 0 else "removed_text",
                        "summary": (r.get("short_added_excerpt") or
                                    r.get("short_removed_excerpt") or "")[:200],
                    }],
                    "confidence": 0.9 if i == 0 else 0.75,
                })
            out.append({
                "family": family,
                "group_id": r["group_id"],
                "meaningful_behavior_change": r["meaningful_behavior_change"],
                "motifs": motifs,
                "notes": "",
            })
    out_path = BASE / "agent-pass-a.jsonl"
    with out_path.open("w", encoding="utf-8") as fh:
        for record in out:
            fh.write(json.dumps(record, ensure_ascii=False) + "\n")
    print("pass-a records:", len(out))


ROOT_SD = Path(__file__).resolve().parents[3] / "research" / "evidence-motifs" / "group_records_annotated.json"
ROOT_FD = Path(__file__).resolve().parents[3] / "research" / "evidence-motifs" / "frontend-design" / "frontend-design-group-records-annotated.json"
ROOT_BS = Path(__file__).resolve().parents[3] / "research" / "evidence-motifs" / "brainstorming" / "brainstorming-group-records-annotated.json"

if __name__ == "__main__":
    main()
